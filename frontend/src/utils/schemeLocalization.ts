export function localizeSchemeRecommendation<T extends SchemeRecommendation>(rec: T, language: AppLanguage): T {
  if (language !== 'ta') return rec;

  const localized = SCHEME_COPY_TA[rec.scheme.scheme_id];
  const localizedName = FALLBACK_NAME_MAP[rec.scheme.scheme_name] ?? rec.scheme.scheme_name;

  return {
    ...rec,
    reason: localized?.reason || 'இந்த திட்டம் உங்கள் சுயவிவரத்துடன் பொருந்துகிறது.',
    scheme: {
      ...rec.scheme,
      scheme_name: localized?.scheme_name || localizedName,
      ministry: localized?.ministry || rec.scheme.ministry,
      description: localized?.description || rec.scheme.description,
      benefits: localized?.benefits || rec.scheme.benefits,
      eligibility: localized?.eligibility || rec.scheme.eligibility,
    },
  };
}

export function localizeSchemeList<T extends SchemeRecommendation>(items: T[], language: AppLanguage): T[] {
  return items.map((item) => localizeSchemeRecommendation(item, language));
}
